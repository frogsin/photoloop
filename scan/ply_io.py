"""PLY 点云读写（零外部依赖）"""

from __future__ import annotations

import struct
from pathlib import Path

import numpy as np

# 属性名 -> numpy dtype 字符
_TYPE_MAP = {
    "char": "i1", "int8": "i1",
    "uchar": "u1", "uint8": "u1",
    "short": "i2", "int16": "i2",
    "ushort": "u2", "uint16": "u2",
    "int": "i4", "int32": "i4",
    "uint": "u4", "uint32": "u4",
    "float": "f4", "float32": "f4",
    "double": "f8", "float64": "f8",
}

_COLOR_NAMES = {"red", "green", "blue", "r", "g", "b"}
_NORMAL_NAMES = {"nx", "ny", "nz"}


def write_ply(path: str | Path, data: dict[str, np.ndarray], ascii: bool = False) -> None:
    """写 PLY 点云。

    data 的键是属性名，例如 x/y/z、nx/ny/nz、red/green/blue。
    所有数组长度必须一致。

    约定：如果存在法向（nx/ny/nz），写入文件头，Poisson 重建才能用。
    """
    names = [k for k in ("x", "y", "z", "nx", "ny", "nz", "red", "green", "blue") if k in data]
    if not names:
        raise ValueError("data 中没有可写属性")

    n = len(data[names[0]])
    for k in names:
        if len(data[k]) != n:
            raise ValueError(f"属性 {k} 长度不一致")

    # 决定存储类型
    dtypes = {}
    for k in names:
        arr = np.asarray(data[k])
        if k in _COLOR_NAMES:
            dtypes[k] = np.uint8
        elif k in _NORMAL_NAMES:
            dtypes[k] = np.float32
        elif np.issubdtype(arr.dtype, np.floating):
            dtypes[k] = np.float32
        else:
            dtypes[k] = arr.dtype

    fmt = "ascii" if ascii else "binary_little_endian"
    lines = [
        "ply",
        f"format {fmt} 1.0",
        "comment generated by photoloop",
        f"element vertex {n}",
    ]
    for k in names:
        t = np.dtype(dtypes[k])
        ptype = {np.dtype("u1"): "uchar", np.dtype("f4"): "float",
                 np.dtype("f8"): "double", np.dtype("i4"): "int"}.get(t, "float")
        lines.append(f"property {ptype} {k}")
    lines.append("end_header")

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    if ascii:
        cols = [np.asarray(data[k]).astype(dtypes[k]) for k in names]
        with open(path, "w", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
            blocks = []
            for k, dt in dtypes.items():
                blocks.append(np.asarray(data[k]).astype(dt))
            stack = np.stack(blocks, axis=1)
            fmt_str = " ".join("%d" if np.issubdtype(dtypes[k], np.integer) else "%.6f" for k in names)
            for row in stack:
                f.write(fmt_str % tuple(row) + "\n")
    else:
        struct_fmt = "<" + "".join(np.dtype(dtypes[k]).char for k in names)
        rec = np.zeros(n, dtype=[(k, dtypes[k]) for k in names])
        for k in names:
            rec[k] = np.asarray(data[k]).astype(dtypes[k])
        with open(path, "wb") as f:
            f.write(("\n".join(lines) + "\n").encode("ascii"))
            f.write(rec.tobytes())


def read_ply(path: str | Path) -> dict[str, np.ndarray]:
    """读 PLY 点云，返回属性字典。支持 ascii / binary_little_endian。"""
    path = Path(path)
    with open(path, "rb") as f:
        if f.readline().strip() != b"ply":
            raise ValueError("不是 PLY 文件")

        fmt = None
        elements: list[tuple[str, int, list[tuple[str, str]]]] = []
        while True:
            raw = f.readline()
            if not raw:
                raise ValueError("PLY 文件头不完整")
            line = raw.strip().decode("ascii", errors="replace")
            if line.startswith("format"):
                fmt = line.split()[1]
            elif line.startswith("element"):
                _, name, cnt = line.split()
                elements.append((name, int(cnt), []))
            elif line.startswith("property"):
                parts = line.split()
                if parts[1] == "list":
                    elements[-1][2].append(("list", parts[-1]))
                else:
                    elements[-1][2].append((parts[1], parts[2]))
            elif line == "end_header":
                break

        out: dict[str, np.ndarray] = {}
        for name, cnt, props in elements:
            if name != "vertex":
                # 忽略面等其他元素（不常见于点云）
                break
            simple = [(t, n) for t, n in props if t != "list"]
            if fmt == "ascii":
                data = [f.readline().split() for _ in range(cnt)]
                arr = np.array(data, dtype=object)
                for i, (t, n) in enumerate(simple):
                    out[n] = arr[:, i].astype(_TYPE_MAP.get(t, "f4"))
            else:
                dt = np.dtype([(n, _TYPE_MAP.get(t, "f4")) for t, n in simple])
                buf = f.read(dt.itemsize * cnt)
                rec = np.frombuffer(buf, dtype=dt, count=cnt)
                for _, n in simple:
                    out[n] = rec[n]
        return out
